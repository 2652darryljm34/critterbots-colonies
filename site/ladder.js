/* Renders ladder/results.json (written by tools/run_ladder.py). #bot=<name> shows one bot. Plain DOM, no libraries. */
(function () {
  'use strict';
  var $ = function (id) { return document.getElementById(id); };
  function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return {'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;'}[c]; }); }
  function b64(bytes) { var s = ''; for (var i = 0; i < bytes.length; i++) s += String.fromCharCode(bytes[i]); return btoa(s).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, ''); }
  async function pack(o) {                                   // same encoding as play.js: JSON -> deflate-raw -> base64url
    var cs = new Blob([new TextEncoder().encode(JSON.stringify(o))]).stream().pipeThrough(new CompressionStream('deflate-raw'));
    return b64(new Uint8Array(await new Response(cs).arrayBuffer()));
  }
  async function link(row, m, label) {
    if (!m) return '';
    try {
      var code = await (await fetch(row.source)).text();
      return '<a href="play.html#r=' + await pack({v: 1, code: code, opp: m.opp, seed: m.seed}) + '">' + label + ': vs ' + esc(m.opp.replace('.py', '')) + ', seed ' + m.seed + ' (margin ' + m.margin + ')</a>';
    } catch (e) { return ''; }
  }
  async function show(data) {
    var name = (location.hash.match(/^#bot=(.+)$/) || [])[1];
    var row = name && data.bots.filter(function (b) { return b.name === decodeURIComponent(name); })[0];
    if (row) {
      var h = '<p><a href="ladder.html" onclick="setTimeout(function(){location.reload()})">← all bots</a></p><h2>' + esc(row.name) + '</h2><p>Rating ' + row.rating + '% · average stores ' + row.avg_score + ' · <a href="' + esc(row.source) + '">source</a></p>';
      h += '<ul><li>' + (await link(row, row.best, 'Best match') || 'no recipe') + '</li><li>' + (await link(row, row.worst, 'Worst match') || 'no recipe') + '</li></ul>';
      h += '<table><tr><th>vs</th><th>win rate</th></tr>' + Object.keys(row.h2h).map(function (k) { return '<tr><td>' + esc(k) + '</td><td>' + row.h2h[k] + '%</td></tr>'; }).join('') + '</table>';
      $('out').innerHTML = h; return;
    }
    $('out').innerHTML = '<table><tr><th>#</th><th>Bot</th><th>Rating</th><th>Avg stores</th><th>Source</th></tr>' + data.bots.map(function (b, i) {
      return '<tr><td>' + (i + 1) + '</td><td><a href="#bot=' + encodeURIComponent(b.name) + '">' + esc(b.name) + '</a>' + (b.submitted ? '' : ' <span class="mut">(example)</span>') + '</td><td>' + b.rating + '%</td><td>' + b.avg_score + '</td><td><a href="' + esc(b.source) + '">code</a></td></tr>';
    }).join('') + '</table>';
  }
  fetch('ladder/results.json').then(function (r) { if (!r.ok) throw 0; return r.json(); }).then(function (d) {
    $('meta').textContent = 'Last updated ' + d.updated + ' · engine ' + d.engine_version + ' · seeds ' + d.seeds[0] + '-' + d.seeds[d.seeds.length - 1];
    show(d); window.addEventListener('hashchange', function () { show(d); });
  }).catch(function () { $('meta').textContent = 'No ladder results yet. They are generated by tools/run_ladder.py (nightly in GitHub Actions).'; });
})();
